//! Xbox Series shaders to host shaders.
//!
//! An Xbox Series shader is a standard DXBC container ([`dxbc`]). Its `DXIL`
//! part ([`dxil`]) may carry Xbox additions around the LLVM bitcode: an
//! `XDAT` table before it indexing blobs after it, among them `xbop`
//! (compiler options) and the zlib-compressed GFX10 code. The bitcode may use
//! console-only intrinsics, so the GFX10 code is translated in general.

pub mod bvh;
pub mod dxbc;
pub mod dxil;
pub mod emit;
pub mod gfx10;
pub mod io;
pub mod ir;
pub mod native;
pub mod resource;
pub mod spill;
pub mod structure;

/// What this build's translator is, as its build script hashed it (32 hex
/// digits): the crate's sources, manifests, lock file, compiler and build
/// settings (`build.rs` lists them and says why). Two builds with the same
/// fingerprint translate every container to the same host shader under the
/// same settings; `victory-gpu` keys its translated-shader cache on it.
pub const TRANSLATOR_FINGERPRINT: &str = env!("VICTORY_TRANSLATOR_FINGERPRINT");

pub use dxbc::{Container, FourCC, Part};
pub use dxil::{DxilProgram, ShaderKind, XboxExtras};
pub use native::{
    HwStage, NativeProgram, ResourceType, RootParam, RootType, UsedResource, native_programs,
};

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum ShaderError {
    #[error("not a DXBC container")]
    NotDxbc,
    #[error("malformed shader: {0}")]
    Malformed(&'static str),
    #[error("GFX10 code at {offset:#x}: {reason}")]
    Isa { offset: usize, reason: &'static str },
    /// Valid code the translator cannot handle yet: an opcode name or a construct.
    #[error("GFX10 code at {offset:#x}: {what} is not supported")]
    Unsupported { offset: usize, what: &'static str },
}

#[cfg(test)]
#[path = "../fingerprint_inputs.rs"]
mod fingerprint_inputs;

/// The fingerprint's lock and manifest inputs (`fingerprint_inputs.rs`):
/// what another crate of the workspace adds leaves them alone; what this
/// crate is built from changes them.
#[cfg(test)]
mod fingerprint_inputs_tests {
    use super::fingerprint_inputs::{closure_names, lock_closure, manifest_part};

    const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "thiserror"
version = "2.0.21"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aa"
dependencies = [
 "thiserror-impl",
]

[[package]]
name = "thiserror-impl"
version = "2.0.21"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bb"

[[package]]
name = "tracing"
version = "0.1.44"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "cc"

[[package]]
name = "victory-core"
version = "0.1.0"
dependencies = [
 "thiserror",
]

[[package]]
name = "victory-shader"
version = "0.1.0"
dependencies = [
 "thiserror",
 "zlib-rs",
]

[[package]]
name = "zlib-rs"
version = "0.6.8"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "dd"
"#;

    #[test]
    fn the_closure_holds_this_crate_and_what_it_links() {
        let names = closure_names(LOCK, "victory-shader");
        assert_eq!(names, ["thiserror", "thiserror-impl", "victory-shader", "zlib-rs"]);
    }

    #[test]
    fn another_crates_new_dependency_leaves_the_lock_part_alone() {
        let before = lock_closure(LOCK, "victory-shader");
        // victory-core takes `tracing`, as the asynchronous log did.
        let after = LOCK.replace(" \"thiserror\",\n]\n\n[[package]]\nname = \"victory-shader\"", " \"thiserror\",\n \"tracing\",\n]\n\n[[package]]\nname = \"victory-shader\"");
        assert_ne!(after, LOCK, "the edit applies");
        assert_eq!(lock_closure(&after, "victory-shader"), before);
        // A crate nothing of ours links, added.
        let added = format!("{LOCK}\n[[package]]\nname = \"walkdir\"\nversion = \"2.5.1\"\n");
        assert_eq!(lock_closure(&added, "victory-shader"), before);
    }

    #[test]
    fn a_dependency_of_this_crate_changing_changes_the_lock_part() {
        let before = lock_closure(LOCK, "victory-shader");
        assert_ne!(lock_closure(&LOCK.replace("0.6.8", "0.6.9"), "victory-shader"), before, "a version");
        assert_ne!(lock_closure(&LOCK.replace("checksum = \"bb\"", "checksum = \"b0\""), "victory-shader"), before, "a transitive checksum");
        assert_ne!(
            lock_closure(&LOCK.replace(" \"zlib-rs\",\n]", " \"zlib-rs\",\n \"tracing\",\n]"), "victory-shader"),
            before,
            "a new dependency of this crate's"
        );
    }

    #[test]
    fn the_manifest_part_keeps_profiles_and_this_crates_lines_only() {
        let manifest = "[workspace]\nresolver = \"3\"\n\n[workspace.dependencies]\n# a comment\nthiserror = \"2.0.21\"\ntracing = \"0.1.44\"\nzlib-rs = { version = \"0.6.8\" }\n\n[workspace.lints.clippy]\nall = \"warn\"\n\n[profile.release]\ndebug = \"line-tables-only\"\n";
        let names = closure_names(LOCK, "victory-shader");
        let part = manifest_part(manifest, &names);
        assert_eq!(
            part,
            "[workspace]\nresolver = \"3\"\nthiserror = \"2.0.21\"\nzlib-rs = { version = \"0.6.8\" }\n[profile.release]\ndebug = \"line-tables-only\"\n"
        );
        assert_eq!(manifest_part(&manifest.replace("0.1.44", "0.1.45"), &names), part, "an unrelated crate's version");
        assert_ne!(manifest_part(&manifest.replace("\"2.0.21\"", "\"2.0.22\""), &names), part, "this crate's dependency");
        assert_ne!(manifest_part(&manifest.replace("line-tables-only", "true"), &names), part, "a profile");
    }

    /// Over the workspace's own files: the closure has this crate and its
    /// two direct dependencies, and not the crates only others take.
    #[test]
    fn the_real_lock_closure_is_this_crates() {
        let lock = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/../../Cargo.lock")).unwrap();
        let names = closure_names(&lock, "victory-shader");
        for want in ["victory-shader", "thiserror", "zlib-rs"] {
            assert!(names.iter().any(|n| n == want), "{want} missing: {names:?}");
        }
        for not in ["tracing", "blake3", "clap", "victory-gpu", "victory-core"] {
            assert!(!names.iter().any(|n| n == not), "{not} is not this crate's: {names:?}");
        }
    }
}
